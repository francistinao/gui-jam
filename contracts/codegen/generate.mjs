import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const contractsDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(contractsDir, '..');

const ROOT_SCHEMAS = [
  'edit-op.schema.json',
  'variant-set.schema.json',
  'update-result.schema.json',
  'element-style.schema.json',
  'finetune.schema.json',
  'ws-protocol.schema.json',
];

const OUTPUTS = {
  bundle: join(contractsDir, 'generated', 'contracts.bundle.schema.json'),
  variantSet: join(contractsDir, 'generated', 'variant-set.provider.schema.json'),
  ts: join(repoRoot, 'packages', 'contracts-ts', 'src', 'generated', 'contracts.ts'),
};

const BANNER =
  '// Generated by contracts/codegen/generate.mjs from contracts/*.schema.json. Do not edit.';

async function loadSchemas() {
  const byFile = new Map();
  for (const file of ROOT_SCHEMAS) {
    byFile.set(file, JSON.parse(await readFile(join(contractsDir, file), 'utf8')));
  }
  return byFile;
}

// Folds every root schema and its $defs into one $defs table so that cross-file refs
// ("edit-op.schema.json") become local ("#/$defs/EditOp"). Provider CLIs and typify
// both need a self-contained schema.
function bundle(byFile) {
  const titleByFile = new Map([...byFile].map(([file, schema]) => [file, schema.title]));
  const defs = {};

  const rewriteRefs = (node) => {
    if (Array.isArray(node)) return node.map(rewriteRefs);
    if (node === null || typeof node !== 'object') return node;
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      const [refFile, refPointer] = key === '$ref' ? String(value).split('#', 2) : [];
      if (refFile && titleByFile.has(refFile)) {
        out[key] = refPointer ? `#${refPointer}` : `#/$defs/${titleByFile.get(refFile)}`;
      } else {
        out[key] = rewriteRefs(value);
      }
    }
    return out;
  };

  const addDef = (name, schema) => {
    if (name in defs) throw new Error(`Duplicate contract definition name: ${name}`);
    defs[name] = rewriteRefs(schema);
  };

  for (const schema of byFile.values()) {
    const { $schema: _schema, $id: _id, $defs: nested = {}, ...rootBody } = schema;
    addDef(schema.title, rootBody);
    for (const [name, def] of Object.entries(nested)) addDef(name, def);
  }
  return defs;
}

// No $schema: Claude Code's --json-schema validator rejects the 2020-12 meta-schema URI
// (verified on 2.1.325, see docs/adr/0004). The keywords used are draft-07 compatible.
function rootedAt(title, defs) {
  const { [title]: root, ...rest } = defs;
  return { ...root, $defs: rest };
}

function pruneUnreferenced(schema) {
  const reachable = new Set();
  const visit = (node) => {
    if (Array.isArray(node)) return node.forEach(visit);
    if (node === null || typeof node !== 'object') return;
    for (const [key, value] of Object.entries(node)) {
      if (key === '$ref' && typeof value === 'string' && value.startsWith('#/$defs/')) {
        const name = value.slice('#/$defs/'.length);
        if (!reachable.has(name)) {
          reachable.add(name);
          visit(schema.$defs[name]);
        }
      } else if (key !== '$defs') {
        visit(value);
      }
    }
  };
  visit(schema);
  const $defs = Object.fromEntries(Object.entries(schema.$defs).filter(([n]) => reachable.has(n)));
  return { ...schema, $defs };
}

async function generateTs(defs) {
  const source = {
    title: 'GuiJamContracts',
    type: 'object',
    additionalProperties: false,
    properties: Object.fromEntries(
      Object.keys(defs).map((name) => [name, { $ref: `#/$defs/${name}` }]),
    ),
    $defs: defs,
  };
  const ts = await compile(source, 'GuiJamContracts', {
    bannerComment: BANNER,
    additionalProperties: false,
    unreachableDefinitions: true,
    strictIndexSignatures: true,
    format: true,
    style: { singleQuote: true, printWidth: 100 },
  });
  const referencedBy = String.raw`This interface was referenced by \`GuiJamContracts\`'s JSON-Schema\n \* via the \`definition\` "\w+"\.`;
  return ts
    .replace(/export interface GuiJamContracts \{[^}]*\}\n\n?/, '')
    .replace(new RegExp(String.raw`/\*\*\n \* ${referencedBy}\n \*/\n`, 'g'), '')
    .replace(new RegExp(String.raw`\n \*\n \* ${referencedBy}`, 'g'), '');
}

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;

async function main() {
  const checkOnly = process.argv.includes('--check');
  const defs = bundle(await loadSchemas());

  const files = new Map([
    [OUTPUTS.bundle, json({ $comment: BANNER.slice(3), $defs: defs })],
    [OUTPUTS.variantSet, json(pruneUnreferenced(rootedAt('VariantSet', defs)))],
    [OUTPUTS.ts, await generateTs(defs)],
  ]);

  const stale = [];
  for (const [path, content] of files) {
    const current = await readFile(path, 'utf8').catch((error) => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (current === content) continue;
    if (checkOnly) {
      stale.push(path);
    } else {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, content);
    }
  }

  if (stale.length > 0) {
    console.error('Generated contracts are out of date. Run `pnpm contracts:gen`:');
    for (const path of stale) console.error(`  ${path}`);
    process.exit(1);
  }
}

await main();
